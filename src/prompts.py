"""
[M2] 评分量表（rubric）

这是整个项目里最需要「想清楚」的文件 —— 大模型判得准不准，全看这里的标准写得够不够硬。

三个设计要点（面试可以直接讲）：
    1. 只看「用户问的那件事有没有被回答」，明确排除态度、长度、是否查了账户这些干扰项。
       —— 因为大模型天然会偏爱礼貌、详细、看起来很努力的答案。
    2. 分档要可判定。5 分和 4 分的差别是「口径完不完整」，不是「感觉好不好」。
    3. 强制输出 JSON 且限定字段。否则模型会开始聊天，后面的代码没法解析。

运行方式：本文件不单独运行，被 src/llm_judge.py 调用。
"""

# ============================================================
# 系统提示：定义角色和总原则
# ============================================================

SYSTEM_PROMPT = (
    "你是一名 AI 客服质量评审员，负责判定智能客服的回答是否真正解决了用户的问题。"
    "你的判断必须严格依据给定的评分标准，不受回答的长度、语气、礼貌程度影响。"
    "你只输出 JSON，不输出任何其他文字。"
)


# ============================================================
# 评分标准：分档细则
# ============================================================
# 注意：这些判据不是凭空想的，是从 30 轮真实实测的错例里倒推出来的。
# 比如「问句里带前提条件的要单开分支」这条，对应的是第 16 题（手机号已注销）。

RUBRIC = """评分标准（只看用户问的那件事有没有被回答）：

5 分 —— 直接回答了核心诉求，且给出完整口径（分档 / 时长 / 具体操作路径）
4 分 —— 回答了核心诉求，但口径不完整（如只说个大概，没给分档或没给路径）
3 分 —— 部分相关，但答的不是用户问的那件事
2 分 —— 转向了其他话题或动作（如直接让用户去查订单、查记录）
1 分 —— 答非所问，或只给一个转人工入口
0 分 —— 拒答、答错，或给了错误信息

判定时必须遵守的补充规则：
- 不要因为回答礼貌、详细、语气好而加分。
- 不要因为「它查了用户账户」算作答对 —— 查账户只是动作，不是回答。
- 问句里带前提条件的（如「手机号已注销」「账户已冻结」），
  必须看回答有没有针对这个前提单独给出分支方案。只给常规主路径的，判 3 分以下。
- 问「能不能 / 可不可以」的，回答必须给出明确结论；
  只讲「怎么做」而不讲「能不能」的，判 3 分以下。
- 问时效（多久 / 什么时候）的，回答必须给出具体时间口径；
  只说「请查看进度」「以实际为准」的，判 3 分以下。
"""


# ============================================================
# 错因标签：与原始数据保持一致的分类体系
# ============================================================

REASON_TAGS = """错因标签，只能从下面四个里选一个：
- 意图识别错：把 A 问题理解成了 B 问题
- 语料未覆盖：回答通顺，但内容答的不是用户问的那件事
- 知识库缺失：直接说不知道，或让用户找人工
- 不适用：回答正确，无需归因
"""


# ============================================================
# 输出格式约束
# ============================================================

OUTPUT_FORMAT = """只输出一个 JSON 对象，不要 markdown 代码块，不要任何解释文字，格式严格如下：
{"score": 整数0到5, "reason_tag": "上面四个标签之一", "reason": "30字以内的判断理由"}"""


def build_messages(question: str, answer: str) -> list[dict]:
    """把一次问答拼成发给大模型的 messages。

    拆成 system + user 两个角色，是各家大模型通用的对话格式。
    system 放角色和原则，user 放具体要评的内容。
    """
    user_content = (
        f"请评估下面这轮 AI 客服对话。\n\n"
        f"【用户提问】\n{question}\n\n"
        f"【AI 应答】\n{answer}\n\n"
        f"{RUBRIC}\n"
        f"{REASON_TAGS}\n"
        f"{OUTPUT_FORMAT}"
    )

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_content},
    ]
